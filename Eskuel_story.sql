CREATE TABLE EXPLORERS (
    explorer_id INT PRIMARY KEY,
    name VARCHAR(50),
    age INT,
    rank VARCHAR(30),
    join_date DATE
);

CREATE TABLE MISSION_LOGS ( 
  log_id INT PRIMARY KEY, 
  explorer_id INT, 
  mission_date DATE, 
  power_draw INT, 
  anomalous BOOLEAN, 
  FOREIGN KEY (explorer_id) REFERENCES EXPLORERS(explorer_id)
);


